#!/usr/bin/env python3
"""Build the pipeline risk readout from the SYNTHETIC sample workbook, for checking the HTML without a warehouse.

    python build_sample_dashboard.py [--out ../../../docs/pipeline_risk_readout_sample.html] [--workbook path.xlsx]
                                     [--as-of YYYY-MM] [--window MTD|QTD|YTD|LTM] [--regenerate]

Uses assets/sample-data/gtm_sample.xlsx (generated by make_sample_data.py when missing, or with --regenerate),
builds the payload with the prototype engine (scripts/gtm/engine.py) and renders one self-contained offline HTML
file with the GTM renderer (artifacts/gtm_analytics/). The page is the engine reading unless --diagnosis passes an AI review
written against this payload (it must pass the admission gate); views without one say "This view not AI reviewed".
Every figure is invented; the page carries the LOCAL TEST DATA banner.
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from gtm import engine                                  # noqa: E402
from gtm.common import BuildError                       # noqa: E402
from gtm.diagnosis import admit                         # noqa: E402
from gtm.render import render                           # noqa: E402

SAMPLE = os.path.join(SKILL, "assets", "sample-data", "gtm_sample.xlsx")
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.dirname(SKILL)), "docs", "pipeline_risk_readout_sample.html")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--workbook", default=SAMPLE)
    ap.add_argument("--as-of")
    ap.add_argument("--window", choices=engine.WINDOWS)
    ap.add_argument("--payload-out", help="also write the payload JSON here")
    ap.add_argument("--regenerate", action="store_true", help="rewrite the sample workbook first")
    ap.add_argument("--diagnosis", nargs="*", default=[], help="diagnosis.json file(s) written against this payload")
    a = ap.parse_args()
    if a.regenerate or (a.workbook == SAMPLE and not os.path.exists(SAMPLE)):
        subprocess.run([sys.executable, os.path.join(HERE, "make_sample_data.py")], check=True)
    try:
        p = engine.build(a.workbook, as_of=a.as_of, window=a.window,
                         title="GTM review", source=f"{os.path.basename(a.workbook)} (local test workbook)")
        review = admit(p, a.diagnosis, allow_missing=True)
        page_bytes = render(p, a.out)
    except BuildError as e:
        print(json.dumps({"ok": False, "error": str(e)}))
        return 1
    if a.payload_out:
        json.dump(p, open(a.payload_out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps({"ok": True, "out": os.path.abspath(a.out), "bytes": page_bytes, "as_of": p["meta"]["as_of"]["label"], "opens_on": p["meta"]["primary_lens"]["id"],
                      "headline": p["lenses"][p["meta"]["primary_lens"]["id"]]["headline"]["text"], "analysis_hash": p["analysis_hash"][:12], "review": review}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
