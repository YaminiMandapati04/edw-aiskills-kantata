#!/usr/bin/env python3
"""Build the budget vs actuals readout from the SYNTHETIC sample workbook, for checking the HTML without a warehouse
or uploading the skill.

    python build_sample_dashboard.py [--out <file.html>] [--baseline] [--regenerate]

Uses assets/sample-data/finance_sample.xlsx (generated by make_sample_data.py when missing, or with --regenerate),
runs analyze_finance.py on it, admits the example diagnosis from test_finance_pipeline.py (unless --baseline) and
renders with the current template, CSS and JS. Default output: <repo>/docs/budget_vs_actuals_readout_sample.html.
Every figure is invented. Never present this page as real.
"""
import argparse
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
sys.path.insert(0, HERE)
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
from test_finance_pipeline import run, example_diagnosis          # noqa: E402

SAMPLE_DIR = os.path.join(SKILL, "assets", "sample-data")
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.dirname(SKILL)), "docs", "budget_vs_actuals_readout_sample.html")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT, help="output .html file (default: docs/budget_vs_actuals_readout_sample.html)")
    ap.add_argument("--baseline", action="store_true", help="render the engine baseline only, without the example diagnosis")
    ap.add_argument("--regenerate", action="store_true", help="rewrite the sample workbooks first")
    a = ap.parse_args()
    wb = os.path.join(SAMPLE_DIR, "finance_sample.xlsx")
    if a.regenerate or not os.path.exists(wb):
        code, log = run(["make_sample_data.py", SAMPLE_DIR])
        if code:
            print(log); return 1
    work = tempfile.mkdtemp(prefix="sda-sample-")
    payload_path = os.path.join(work, "finance_payload.json")
    code, log = run(["analyze_finance.py", "--workbook", wb, "--out", payload_path, "--expect-accounts", "12"])
    if code:
        print(log); return 1
    cmd = ["render_finance_dashboard.py", "--payload", payload_path, "--out", a.out]
    if a.baseline:
        cmd += ["--allow-missing-review"]
    else:
        # the renderer needs an admitted review for the Month and the Year-to-date views
        payload = json.load(open(payload_path, encoding="utf-8"))
        cmd += ["--diagnosis"]
        for name, lens in (("diagnosis_mtd.json", None), ("diagnosis_ytd.json", "YTD_py")):
            diag_path = os.path.join(work, name)
            json.dump(example_diagnosis(payload, lens), open(diag_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
            cmd += [diag_path]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    code, log = run(cmd)
    print(log.strip().splitlines()[-1] if log.strip() else "")
    if code:
        print(log); return 1
    print(f"Sample dashboard ({'engine baseline' if a.baseline else 'with example diagnosis'}): {os.path.abspath(a.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
